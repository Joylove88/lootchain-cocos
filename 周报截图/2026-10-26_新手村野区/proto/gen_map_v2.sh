#!/usr/bin/env bash
# 传送阵大地图 v2(用户 10-26:「点击传送阵应该显示地图,目前这个地图设计不好看,需要重新设计,大地图,点击某个传送阵位置可传送」)
set -u
cd /d/project/lootchain-cocos
D="周报截图/2026-10-26_新手村野区/proto"
TOWN="周报截图/2026-10-25_主城跑图/proto_v7_camera.png"
FIELD="$D/p2_field.png"
NOAI="不要 AI 感:不要颗粒噪点、不要光束粒子、不要炫光、不要满屏发光点,装饰克制,像真实上线的游戏截图;所有中文为简体且清晰可读,字不要多。"
COMMON="整屏就是一张大地图,地图占满画面,不要左右分栏、不要大信息面板。
地图上的地理位置(从左下到右上大致沿一条主路):左下是绿色山谷里的小村庄「晨风村」;中间偏左是一座有城墙的大城「主城」(地图上最醒目);主城东边是灰褐色碎石荒原「灰岩荒原」;再往东北是枯死的黑色森林「枯木林」;北边是冒着暗红熔岩光的矿坑「熔渣矿坑」;左上是积雪的山脉高地「霜脊高地」;右上角是一条巨大龙骨横卧的峡谷「龙骸深谷」;地图边缘是海和云雾。
每个地点上都画着一个小的圆形传送阵图标(石质圆盘 + 淡蓝符文,俯视压扁,带一个小的发光底座),旁边一个小名牌写地名和等级段,例如「灰岩荒原 Lv.10-20」。
状态表达:已激活的传送阵符文亮蓝色;还没激活的传送阵是暗灰色;未解锁的区域被深色云雾半盖住,名牌上带一个小锁和「Lv.30 开放」;晨风村整体去色变灰,名牌写「已离开」。
当前位置:主城传送阵上插一个小的玩家头像定位针。
玩家点中了「灰岩荒原」的传送阵:这个图标有一圈金色选中光环,旁边弹出一张小气泡卡片(深色底细金边,宽度约占屏幕 1/5):标题「灰岩荒原」、一行「推荐等级 10-20」、一行 3 个小怪物圆头像、一行小字「剧情任务『荒原的威胁』在此」、底部一个红底金边按钮「传送」。
HUD 只有:左上红底金边返回横幅「< 世界地图」;右上体力胶囊和圆形关闭钮;右下角一个小的缩放按钮(+ / -)。"

cat > "$D/p3_map_a.txt" <<EOF
生成一张 2400x1080 横屏手游界面原型图。这是「世界地图」:玩家在任意传送阵上打开,点地图上的传送阵直接传送。
画风 A:写实手绘的奇幻大陆地图,俯视正上方视角,地形用细腻的厚涂表现(山脉有体积、森林是成片树冠、河流反光、道路是土路),整体偏暗、低饱和,和参考图(同一款游戏的主城与野区)色调一致;不是羊皮纸,不是简笔画。
$COMMON
$NOAI
EOF

cat > "$D/p3_map_b.txt" <<EOF
生成一张 2400x1080 横屏手游界面原型图。这是「世界地图」:玩家在任意传送阵上打开,点地图上的传送阵直接传送。
画风 B:一整块漂浮在云海上的立体沙盘大陆,斜 45 度俯视(和参考图同一款游戏的主城、野区同一个镜头角度),每个区域是有体积的微缩场景(主城的城墙和塔楼、荒原的碎石、枯木林的枯树、熔渣矿坑的矿架与熔岩、霜脊高地的雪山、龙骸深谷的龙骨),区域之间有土路相连,大陆边缘是断崖和云海;整体偏暗、低饱和,只有传送阵符文和熔岩是亮的。
$COMMON
$NOAI
EOF

run() {
  local name=$1; shift
  [ -f "$D/$name.png" ] && { echo "skip $name"; return; }
  python tools/qa/gen_proto.py --prompt "$D/$name.txt" --out "$D/$name.png" --ref "$@" 2>&1 | tail -1
}
run p3_map_a "$TOWN" "$FIELD"
run p3_map_b "$TOWN" "$FIELD"
echo ALL-DONE
